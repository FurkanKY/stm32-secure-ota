"""Ed25519 key handling and export of the public key for the bootloader."""

from __future__ import annotations

from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)


def generate(path: Path, passphrase: bytes | None = None) -> Ed25519PrivateKey:
    key = Ed25519PrivateKey.generate()
    encryption = (
        serialization.BestAvailableEncryption(passphrase)
        if passphrase
        else serialization.NoEncryption()
    )
    pem = key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, encryption
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(pem)
    return key


def load_private(path: Path, passphrase: bytes | None = None) -> Ed25519PrivateKey:
    key = serialization.load_pem_private_key(path.read_bytes(), password=passphrase)
    if not isinstance(key, Ed25519PrivateKey):
        raise ValueError(f"{path} is not an Ed25519 private key")
    return key


def load_public(path: Path) -> Ed25519PublicKey:
    """Accept a private key PEM, a public key PEM or a raw 32-byte key."""
    data = path.read_bytes()
    if len(data) == 32:
        return Ed25519PublicKey.from_public_bytes(data)
    if b"PRIVATE KEY" in data:
        return load_private(path).public_key()
    key = serialization.load_pem_public_key(data)
    if not isinstance(key, Ed25519PublicKey):
        raise ValueError(f"{path} is not an Ed25519 public key")
    return key


def raw_public(key: Ed25519PublicKey) -> bytes:
    return key.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def to_c_source(key: Ed25519PublicKey, symbol: str = "boot_pubkeys") -> str:
    """C translation unit holding the key table that the bootloader links in."""
    raw = raw_public(key)
    rows = ",\n".join(
        "        " + ", ".join(f"0x{b:02x}" for b in raw[i:i + 8]) for i in range(0, 32, 8)
    )
    return (
        "/* Generated by `otatool pubkey --c`. Do not edit. */\n"
        "#include <stdint.h>\n\n"
        '#include "boot_keys.h"\n\n'
        f"const uint8_t {symbol}[][32] = {{\n"
        "    {\n"
        f"{rows}\n"
        "    },\n"
        "};\n\n"
        f"const unsigned {symbol}_count = sizeof({symbol}) / sizeof({symbol}[0]);\n"
    )
